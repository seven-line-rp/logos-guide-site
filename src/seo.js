export function pageTitle(title) {
  return title ? `${title} | ${SITE_NAME}` : HOME_TITLE
}

const escapeAttr = (value) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
// Копия index.html для страницы path: свои title, description, canonical и og-теги.
// Если в index.html пропал какой-то тег, сборка падает, а не пишет страницу без него.
export function pageHtml(html, path) {
  const page = PAGES[path]
  const title = escapeAttr(pageTitle(page.title))
  const description = escapeAttr(page.description)
  const url = `${SITE_URL}${path}`
  const swaps = [
    [/<title>[^<]*<\/title>/, `<title>${title}</title>`],
    [/(<meta name="description" content=")[^"]*(")/, `$1${description}$2`],
    [/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`],
    [/(<meta property="og:title" content=")[^"]*(")/, `$1${title}$2`],
    [/(<meta property="og:description" content=")[^"]*(")/, `$1${description}$2`],
    [/(<meta property="og:url" content=")[^"]*(")/, `$1${url}$2`],
  ]
  return swaps.reduce((result, [pattern, value]) => {
    if (!pattern.test(result)) throw new Error(`index.html: не найден тег ${pattern} для страницы ${path}`)
    return result.replace(pattern, value)
  }, html)
}
