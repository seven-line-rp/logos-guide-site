import { SITE_VERSION } from '../version.js'

// Адрес файла ролика (public/promo) с версией сайта, например ?v=1.11.0.
// Ролики пересобираются под теми же именами, и без метки браузер (или старый
// сервис-воркер) мог показывать прошлую версию — например, промо-ролик без
// рекламной паузы. С новой версией сайта адрес новый, и файл берётся заново.
export const fresh = (path) => `${path}?v=${SITE_VERSION}`
