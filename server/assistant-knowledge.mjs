import { navigation, rooms } from '../src/data.js'
import { openDayVenues } from '../src/openDay.js'

const roomFacts = rooms.map((room) => {
  const number = room.number ? ` №${room.number}` : ''
  const mapLink = `/map?floor=${room.floor}&room=${encodeURIComponent(room.id)}`
  return `- ${room.name}${number} — ${room.floor} этаж. ${room.description} Карта: ${mapLink}`
}).join('\n')

const pageFacts = navigation.map((item) => `${item.label} — ${item.to}`).join('\n')
const openDayFacts = openDayVenues.map((venue) => {
  const room = rooms.find((item) => item.id === venue.roomId)
  const location = room ? `${room.floor} этаж${room.number ? `, №${room.number}` : ''}` : 'место указано в каталоге'
  return `- ${venue.title} — ${location}. ${venue.description} ${venue.leader}.`
}).join('\n')

